/**
 * Standalone build-output security scanner for the static dashboard
 * (ADR-0011 P4-1).
 *
 *   scanBuildOutput(dir, deps) -> ScanResult
 *
 * Read-only inspection of ONE completed `scripts/build-dashboard.ts` output
 * directory, named explicitly. It never discovers, follows, mutates,
 * deletes, normalizes or rewrites anything, never executes the scanned
 * JavaScript and never makes a network request.
 *
 * Checks, all against the committed eight-file output contract:
 *
 *   1 filesystem  exactly the eight files in exactly three directories; no
 *                 symlinks, other file types or extra entries; each file read
 *                 through one O_NOFOLLOW handle, size-limited and unchanged
 *                 while read
 *   2 HTML        exactly one script element, the approved module script;
 *                 the exact committed Content Security Policy (with
 *                 `connect-src 'none'`); no inline handlers, frames, objects,
 *                 embeds or non-local references
 *   3 JavaScript  no network, dynamic-code, storage or HTML-injection APIs;
 *                 every import is relative and resolves to one of the
 *                 output's own modules
 *   4 data        `dashboard/publication-data.js` has exactly the generated
 *                 header and the two exports; state `none` (empty text),
 *                 `embedded` (text accepted by the committed browser-safe
 *                 strict reader, which also refuses non-canonical text and
 *                 contradictory state/reason combinations) or `demo` (the
 *                 same reader plus the ADR-0011 P4 synthetic-only policy;
 *                 `demo-not-synthetic-only` otherwise)
 *   5 leakage     credential, header, signed-URL, storage-host, private-path,
 *                 private-input, build-record, stack-trace, raw-report,
 *                 canary and outbound-URL markers
 *
 * TRUST. A clean scan says the output has the committed shape and contains
 * none of the listed markers. It does NOT authenticate an embedded
 * publication: `BUILD_VERIFIED` remains the publisher's statement, and
 * neither the manifest text nor its SHA-256 proves its origin. The result
 * therefore carries no verdict, authenticity or certificate.
 *
 * Output: fixed codes with counts only. No path, file content, matched
 * value or exception text is returned.
 *
 * Free of `@/` imports so Node's type-stripping test runner can load it
 * directly (ADR-0002).
 */
import { basename, isAbsolute, posix, resolve, sep } from 'node:path';
import ts from 'typescript';

import { nodePublisherFs, type PublisherFs } from './publication-publisher.ts';
import { parsePublication } from './publication-view.ts';
import { isSyntheticOnlyDemo } from './demo-publication.ts';

/* ------------------------------------------------------------------ *
 * Output contract
 * ------------------------------------------------------------------ */

export const OUTPUT_FILES = [
  'dashboard/app.js',
  'dashboard/index.html',
  'dashboard/publication-data.js',
  'dashboard/styles.css',
  'src/reporting/dashboard-model.js',
  'src/reporting/publication-view.js',
  'src/reporting/quality-summary.js',
  'src/reporting/verdict.js',
] as const;

export const OUTPUT_DIRECTORIES = ['dashboard', 'src', 'src/reporting'] as const;

export const DATA_MODULE = 'dashboard/publication-data.js';

/** The CSP the committed `dashboard/index.html` declares, verbatim. */
export const EXPECTED_CSP =
  "default-src 'none'; script-src 'self'; style-src 'self'; img-src 'self'; connect-src 'none'; font-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'";

export const APPROVED_SCRIPT = '<script type="module" src="app.js"></script>';

/** The first line `publicationDataModule` writes (scripts/build-dashboard.ts). */
export const DATA_MODULE_HEADER =
  '// Generated by scripts/build-dashboard.ts (ADR-0011 P3-3). Data only; do not edit.';

/** Per-file limits: sources are capped at 2 MiB by the builder; data holds a 1 MiB manifest. */
export const MAX_FILE_BYTES = 2 * 1024 * 1024;
export const MAX_DATA_MODULE_BYTES = 8 * 1024 * 1024;

const MAX_ENTRIES_PER_DIRECTORY = 64;

/* ------------------------------------------------------------------ *
 * Diagnostics
 * ------------------------------------------------------------------ */

export const SCAN_CODES = [
  // filesystem
  'invalid-directory',
  'directory-missing',
  'symlink-root',
  'not-a-directory',
  'unexpected-entry',
  'missing-file',
  'symlink-entry',
  'non-regular-file',
  'file-too-large',
  'file-unstable',
  'file-unreadable',
  'invalid-encoding',
  // HTML and CSP
  'html-script-count',
  'html-script-not-approved',
  'html-inline-script',
  'csp-missing',
  'csp-mismatch',
  'html-inline-handler',
  'html-embedded-content',
  'html-remote-reference',
  // JavaScript
  'js-forbidden-api',
  'js-external-import',
  'js-unresolved-import',
  // data module
  'data-module-shape',
  'data-module-state',
  'data-module-text',
  'publication-rejected',
  'demo-not-synthetic-only',
  // leakage
  'leak-credential',
  'leak-auth-header',
  'leak-signed-url',
  'leak-storage-host',
  'leak-private-path',
  'leak-private-input',
  'leak-build-record',
  'leak-stack-trace',
  'leak-raw-report',
  'leak-canary',
  'leak-outbound-url',
  // internal
  'internal-error',
] as const;
export type ScanCode = (typeof SCAN_CODES)[number];

export interface Finding {
  readonly code: ScanCode;
  readonly count: number;
}

export type ScanResult =
  | { readonly status: 'clean'; readonly files: number }
  | { readonly status: 'rejected'; readonly findings: readonly Finding[] };

/** Read-only filesystem adapters; production uses `nodePublisherFs` (P2). */
export interface ScannerDeps {
  readonly fs: Pick<PublisherFs, 'lstat' | 'list' | 'readHandle'>;
}

class Findings {
  private readonly counts = new Map<ScanCode, number>();
  add(code: ScanCode, count = 1): void {
    if (count > 0) this.counts.set(code, (this.counts.get(code) ?? 0) + count);
  }
  get empty(): boolean {
    return this.counts.size === 0;
  }
  list(): Finding[] {
    return SCAN_CODES.filter((c) => this.counts.has(c)).map((code) => ({
      code,
      count: this.counts.get(code) ?? 0,
    }));
  }
}

function rejected(findings: Findings): ScanResult {
  return Object.freeze({ status: 'rejected', findings: Object.freeze(findings.list()) });
}

/* ------------------------------------------------------------------ *
 * 1 Filesystem
 * ------------------------------------------------------------------ */

function validDirectoryArgument(dir: unknown): dir is string {
  return (
    typeof dir === 'string' &&
    dir.length > 0 &&
    dir.length <= 4096 &&
    !dir.includes('\0') &&
    isAbsolute(dir) &&
    resolve(dir) === dir &&
    basename(dir) !== '' &&
    !dir.split(sep).includes('..')
  );
}

/**
 * Reads exactly the contract's files without following links. Records
 * filesystem findings and returns the decoded text of every readable file.
 */
function readTree(dir: string, deps: ScannerDeps, out: Findings): Map<string, string> {
  const files = new Map<string, string>();
  const expectedChildren = new Map<string, Set<string>>([['', new Set()]]);
  for (const d of OUTPUT_DIRECTORIES) expectedChildren.set(d, new Set());
  for (const path of [...OUTPUT_DIRECTORIES, ...OUTPUT_FILES]) {
    const parent = posix.dirname(path) === '.' ? '' : posix.dirname(path);
    expectedChildren.get(parent)?.add(posix.basename(path));
  }

  for (const [rel, expected] of expectedChildren) {
    const abs = rel === '' ? dir : `${dir}${sep}${rel.split('/').join(sep)}`;
    if (rel !== '') {
      const info = deps.fs.lstat(abs);
      if (info === undefined) {
        out.add('missing-file');
        continue;
      }
      if (info.kind === 'symlink') {
        out.add('symlink-entry');
        continue;
      }
      if (info.kind !== 'directory') {
        out.add('non-regular-file');
        continue;
      }
    }
    const names = deps.fs.list(abs);
    if (names === undefined || names.length > MAX_ENTRIES_PER_DIRECTORY) {
      out.add(names === undefined ? 'file-unreadable' : 'unexpected-entry');
      continue;
    }
    out.add('unexpected-entry', names.filter((n) => !expected.has(n)).length);
  }

  for (const path of OUTPUT_FILES) {
    const abs = `${dir}${sep}${path.split('/').join(sep)}`;
    const info = deps.fs.lstat(abs);
    if (info === undefined) {
      out.add('missing-file');
      continue;
    }
    if (info.kind === 'symlink') {
      out.add('symlink-entry');
      continue;
    }
    if (info.kind !== 'file') {
      out.add('non-regular-file');
      continue;
    }
    const limit = path === DATA_MODULE ? MAX_DATA_MODULE_BYTES : MAX_FILE_BYTES;
    const read = deps.fs.readHandle(abs, limit);
    if (read.status === 'missing') out.add('missing-file');
    else if (read.status === 'symlink') out.add('symlink-entry');
    else if (read.status === 'not-file') out.add('non-regular-file');
    else if (read.status === 'too-large') out.add('file-too-large');
    else if (read.status !== 'ok') out.add('file-unreadable');
    else if (!read.isFile) out.add('non-regular-file');
    else if (read.bytes.byteLength > limit) out.add('file-too-large');
    else if (!read.stable) out.add('file-unstable');
    else {
      try {
        files.set(path, new TextDecoder('utf-8', { fatal: true }).decode(read.bytes));
      } catch {
        out.add('invalid-encoding');
      }
    }
  }
  return files;
}

/* ------------------------------------------------------------------ *
 * 2 HTML and CSP
 * ------------------------------------------------------------------ */

function stripHtmlComments(html: string): string {
  return html.replace(/<!--[\s\S]*?-->/g, '');
}

export function htmlFindings(html: string, out: Findings): void {
  const markup = stripHtmlComments(html);
  const scripts = markup.match(/<script\b[^>]*>[\s\S]*?<\/script\s*>|<script\b[^>]*\/?>/gi) ?? [];
  if (scripts.length !== 1) out.add('html-script-count');
  for (const s of scripts) {
    const inline = /<script\b[^>]*>([\s\S]*?)<\/script\s*>/i.exec(s);
    if (inline?.[1] !== undefined && inline[1].trim() !== '') out.add('html-inline-script');
    if (s !== APPROVED_SCRIPT) out.add('html-script-not-approved');
  }
  const metas = [...markup.matchAll(/<meta\b[^>]*>/gi)].map((m) => m[0]);
  const csp = metas.filter((m) => /http-equiv\s*=\s*"Content-Security-Policy"/i.test(m));
  if (csp.length !== 1) out.add('csp-missing');
  else {
    const content = /\scontent\s*=\s*"([^"]*)"/i.exec(csp[0] ?? '')?.[1];
    if (content !== EXPECTED_CSP) out.add('csp-mismatch');
  }
  out.add('html-inline-handler', (markup.match(/\son[a-z]+\s*=/gi) ?? []).length);
  out.add(
    'html-embedded-content',
    (markup.match(/<(iframe|frame|object|embed|base)\b/gi) ?? []).length,
  );
  // Every reference is to the output's own stylesheet or script, or an in-page fragment.
  const refs = [...markup.matchAll(/\s(src|href|action|data|srcset|poster)\s*=\s*"([^"]*)"/gi)].map(
    (m) => m[2] ?? '',
  );
  const allowed = (v: string): boolean =>
    v === 'app.js' || v === 'styles.css' || /^#[A-Za-z0-9_-]+$/.test(v);
  out.add('html-remote-reference', refs.filter((v) => !allowed(v)).length);
  if (/\bjavascript:|\burl\s*\(/i.test(markup)) out.add('html-remote-reference');
}

/* ------------------------------------------------------------------ *
 * 3 JavaScript
 * ------------------------------------------------------------------ */

/** The compiled-output prohibitions of scripts/build-dashboard.ts, restated. */
export const FORBIDDEN_JS: readonly RegExp[] = [
  /\binnerHTML\b/,
  /\bouterHTML\b/,
  /\binsertAdjacentHTML\b/,
  /\bdocument\.write/,
  /\beval\s*\(/,
  /\bnew\s+Function\b/,
  /\bFunction\s*\(/,
  /\bfetch\s*\(/,
  /\bXMLHttpRequest\b/,
  /\bWebSocket\b/,
  /\bEventSource\b/,
  /\bsendBeacon\b/,
  /\bimport\s*\(/,
  /\blocalStorage\b/,
  /\bsessionStorage\b/,
  /\bindexedDB\b/,
  /https?:\/\//,
  // Beyond the builder's list: other ways to reach the network or run strings.
  /\bimportScripts\b/,
  /\bnew\s+Worker\b/,
  /\bSharedWorker\b/,
  /\bserviceWorker\b/,
  /\bRTCPeerConnection\b/,
  /\bsetTimeout\s*\(\s*["'`]/,
  /\bsetInterval\s*\(\s*["'`]/,
  /\bdocument\.cookie\b/,
];

export function javascriptFindings(path: string, text: string, out: Findings): void {
  out.add('js-forbidden-api', FORBIDDEN_JS.filter((p) => p.test(text)).length);
  for (const imported of ts.preProcessFile(text, true, true).importedFiles) {
    const spec = imported.fileName;
    if (!spec.startsWith('./') && !spec.startsWith('../')) {
      out.add('js-external-import');
      continue;
    }
    const target = posix.normalize(posix.join(posix.dirname(path), spec));
    if (
      target.startsWith('..') ||
      !target.endsWith('.js') ||
      !(OUTPUT_FILES as readonly string[]).includes(target)
    ) {
      out.add('js-unresolved-import');
    }
  }
}

/* ------------------------------------------------------------------ *
 * 4 Publication data module
 * ------------------------------------------------------------------ */

const DATA_SHAPE =
  /^\/\/ Generated by scripts\/build-dashboard\.ts \(ADR-0011 P3-3\)\. Data only; do not edit\.\nexport const PUBLICATION_STATE = '([a-z]+)';\nexport const PUBLICATION_TEXT = ("(?:[^"\\\n]|\\["\\/bfnrt]|\\u[0-9a-f]{4})*");\n$/;

/** Returns the decoded publication text when the module is valid, else undefined. */
export function dataModuleFindings(text: string, out: Findings): string | undefined {
  const match = DATA_SHAPE.exec(text);
  if (match === null || match[1] === undefined || match[2] === undefined) {
    out.add('data-module-shape');
    return undefined;
  }
  if (!/^[\x20-\x7e\n]*$/.test(text)) {
    out.add('data-module-shape');
    return undefined;
  }
  const state = match[1];
  let decoded: unknown;
  try {
    decoded = JSON.parse(match[2]) as unknown;
  } catch {
    out.add('data-module-shape');
    return undefined;
  }
  if (typeof decoded !== 'string') {
    out.add('data-module-shape');
    return undefined;
  }
  if (state === 'none') {
    if (decoded !== '') out.add('data-module-text');
    return decoded;
  }
  if (state !== 'embedded' && state !== 'demo') {
    out.add('data-module-state');
    return undefined;
  }
  if (decoded === '') {
    out.add('data-module-text');
    return undefined;
  }
  // The committed strict reader: schema, canonical text and reason/state rules.
  // Acceptance is NOT authentication of the publisher's claims.
  const parsed = parsePublication(decoded);
  if (parsed.state !== 'valid') {
    out.add('publication-rejected');
    return decoded;
  }
  // demo (ADR-0011 P4): the synthetic-only policy, never a verification.
  if (state === 'demo' && !isSyntheticOnlyDemo(parsed.manifest)) {
    out.add('demo-not-synthetic-only');
  }
  return decoded;
}

/* ------------------------------------------------------------------ *
 * 5 Leakage
 * ------------------------------------------------------------------ */

const LEAK_RULES: readonly (readonly [ScanCode, RegExp])[] = [
  [
    'leak-credential',
    /\b(?:ghp|gho|ghs|ghu|ghr)_[A-Za-z0-9]{10,}|github_pat_[A-Za-z0-9_]{10,}|QUALITY_VERDICT_GITHUB_TOKEN|-----BEGIN [A-Z ]*PRIVATE KEY-----/,
  ],
  [
    'leak-auth-header',
    /\bauthorization\s*:\s*\S|\bbearer\s+[A-Za-z0-9._~+/-]{8,}|\btoken\s+[A-Za-z0-9_]{20,}/i,
  ],
  [
    'leak-signed-url',
    /[?&](?:sig|se|sv|sp|spr|skoid|sktid|ske|skt|sks|skv|X-Amz-Signature|X-Amz-Credential|X-Goog-Signature|X-Goog-Credential)=/i,
  ],
  [
    'leak-storage-host',
    /blob\.core\.windows\.net|productionresultssa\d*|\.s3[.-][a-z0-9-]*\.?amazonaws\.com|storage\.googleapis\.com|objects\.githubusercontent\.com|pipelines\.actions\.githubusercontent\.com/i,
  ],
  [
    'leak-private-path',
    /\/Users\/[A-Za-z0-9._-]+\/|\/home\/[A-Za-z0-9._-]+\/|\/private\/(?:var|tmp)\/|\/var\/folders\/|\/tmp\/[A-Za-z0-9._-]+|[A-Za-z]:\\\\(?:Users|Documents and Settings)\\\\/,
  ],
  [
    'leak-private-input',
    /QualityPublication|QualityVerdictEvidence|quality-verdict-publication-allowlist|allowListSchemaVersion/i,
  ],
  [
    'leak-build-record',
    /quality-verdict-publication-build-record|buildRecordSchemaVersion|allowListSha256|packageLockSha256/,
  ],
  [
    'leak-stack-trace',
    /\n\s+at\s+[^\n]*:\d+:\d+\)?\s*(?:\n|$)|\b(?:Error|TypeError|RangeError|SyntaxError): [^\n]*\n\s+at\s/,
  ],
  ['leak-canary', /canary/i],
  ['leak-outbound-url', /\b(?:https?|wss?|ftp):\/\//i],
];

/**
 * Raw Playwright report structures: report-only keys, or an `instances`,
 * `executions`, `attempts` or `errors` ARRAY. A numeric `"instances": 99` is
 * a permitted publication metric and never a finding, and the manifest's own
 * `"results": [` array is publication data, not a raw report.
 */
const RAW_REPORT =
  /"(?:stdout|stderr|attachments|suites|specs|titlePath|steps|errorLocation)"\s*:|"(?:instances|executions|attempts|errors)"\s*:\s*\[/;

export function leakFindings(text: string, out: Findings): void {
  for (const [code, pattern] of LEAK_RULES) {
    if (pattern.test(text)) out.add(code);
  }
}

/** Raw-report checks apply to data (HTML and the decoded publication), not to compiled code. */
export function rawReportFindings(text: string, out: Findings): void {
  if (RAW_REPORT.test(text)) out.add('leak-raw-report');
}

/* ------------------------------------------------------------------ *
 * Entry point
 * ------------------------------------------------------------------ */

/** Content checks over already-read files (exposed for tests). */
export function scanContents(files: ReadonlyMap<string, string>, out: Findings): void {
  const html = files.get('dashboard/index.html');
  if (html !== undefined) {
    htmlFindings(html, out);
    leakFindings(html, out);
    rawReportFindings(html, out);
  }
  for (const [path, text] of files) {
    if (!path.endsWith('.js')) continue;
    javascriptFindings(path, text, out);
    if (path === DATA_MODULE) {
      const decoded = dataModuleFindings(text, out);
      if (decoded !== undefined) rawReportFindings(decoded, out);
    }
    leakFindings(text, out);
  }
  const css = files.get('dashboard/styles.css');
  if (css !== undefined) {
    leakFindings(css, out);
    if (/@import\b|url\s*\(\s*["']?(?!#)[^)]*\)/i.test(css)) out.add('html-remote-reference');
  }
}

export { Findings };

/**
 * Scans one explicitly named dashboard output directory. Never throws; a
 * clean result carries only the file count, a rejection only fixed codes
 * with counts.
 */
export function scanBuildOutput(
  dir: unknown,
  deps: ScannerDeps = { fs: nodePublisherFs },
): ScanResult {
  const out = new Findings();
  try {
    if (!validDirectoryArgument(dir)) {
      out.add('invalid-directory');
      return rejected(out);
    }
    const root = deps.fs.lstat(dir);
    if (root === undefined) {
      out.add('directory-missing');
      return rejected(out);
    }
    if (root.kind === 'symlink') {
      out.add('symlink-root');
      return rejected(out);
    }
    if (root.kind !== 'directory') {
      out.add('not-a-directory');
      return rejected(out);
    }
    const files = readTree(dir, deps, out);
    scanContents(files, out);
    if (out.empty && files.size === OUTPUT_FILES.length) {
      return Object.freeze({ status: 'clean', files: files.size });
    }
    if (out.empty) out.add('missing-file');
    return rejected(out);
  } catch {
    const failed = new Findings();
    failed.add('internal-error');
    return rejected(failed);
  }
}

/** The single fixed line the CLI prints. */
export function scanMessage(result: ScanResult): string {
  return result.status === 'clean'
    ? `build-output-scan: clean files=${String(result.files)}`
    : `build-output-scan: rejected ${result.findings.map((f) => `${f.code}=${String(f.count)}`).join(' ')}`;
}
