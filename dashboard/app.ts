type PublicationInput =
  | { readonly kind: 'none' }
  | { readonly kind: 'embedded'; readonly text: string }
  | { readonly kind: 'invalid-module' };

/** The generated module must have exactly its two exports and one of two states. */
function publicationInput(): PublicationInput {
  const module: unknown = generatedPublication;
  if (typeof module !== 'object' || module === null) return { kind: 'invalid-module' };
  if (Object.keys(module).sort().join() !== 'PUBLICATION_STATE,PUBLICATION_TEXT') {
    return { kind: 'invalid-module' };
  }
  const exports = module as Readonly<Record<string, unknown>>;
  const state = exports.PUBLICATION_STATE;
  const text = exports.PUBLICATION_TEXT;
  if (typeof text !== 'string') return { kind: 'invalid-module' };
  if (state === 'none') return text === '' ? { kind: 'none' } : { kind: 'invalid-module' };
  if (state === 'embedded') return { kind: 'embedded', text };
  return { kind: 'invalid-module' };
}

